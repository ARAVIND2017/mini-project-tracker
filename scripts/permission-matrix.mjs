// Renders supabase/tests/permission_matrix.json as docs/PERMISSION_MATRIX.md.
// The same JSON drives supabase/tests/900_permission_matrix.sql, so the table and the
// tests cannot drift apart.
//   node scripts/permission-matrix.mjs           # write the document
//   node scripts/permission-matrix.mjs --check   # fail if the document is out of date (CI)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'supabase/tests/permission_matrix.json');
const target = join(root, 'docs/PERMISSION_MATRIX.md');
const matrix = JSON.parse(readFileSync(source, 'utf8'));
const callers = Object.keys(matrix.callers);
const short = {
  anon: 'Anon',
  student_own: 'Stud. (own)',
  student_other: 'Stud. (other)',
  faculty: 'Faculty',
  guide: 'Guide',
  co_reviewer: 'Co-rev.',
  authorized: 'Auth.',
  expired_auth: 'Exp. auth.',
  lead: 'Lead',
  hod: 'HOD',
  admin_all: 'Admin ⚙',
  admin_none: 'Admin',
  deactivated: 'Deact.',
};

const lines = [
  '# Permission matrix (generated)',
  '',
  '<!-- Generated by scripts/permission-matrix.mjs from supabase/tests/permission_matrix.json. Do not edit by hand. -->',
  '',
  'What each kind of caller may do, as **tested** by `supabase/tests/900_permission_matrix.sql`: every action is run as every caller against one fixture, each attempt rolled back. ✅ = allowed, ❌ = refused (`FORBIDDEN`, `NOT_FOUND` or "permission denied"). The policy itself is described in USER_ROLES_AND_PERMISSIONS.md.',
  '',
  '**Callers**',
  '',
  ...callers.map((c) => `- **${short[c] ?? c}**: ${matrix.callers[c]}`),
  '',
];
const header = `| Action | Function | ${callers.map((c) => short[c] ?? c).join(' | ')} |`;
const rule = `|---|---|${callers.map(() => ':-:').join('|')}|`;
for (const section of matrix.sections) {
  lines.push(`## ${section.title}`, '', header, rule);
  for (const a of section.actions) {
    const cells = callers.map((c) => (a.allow.includes(c) ? '✅' : '❌'));
    lines.push(`| ${a.label} | \`${a.rpc}\` | ${cells.join(' | ')} |`);
  }
  lines.push('');
}
const reads = matrix.reads;
lines.push(
  '## Reading',
  '',
  `- **Project records** (every table and view with a \`project_id\`): ${reads.project_visible.map((c) => short[c] ?? c).join(', ')}. Everyone else sees no rows.`,
  `- **Staff-only project records** (${reads.staff_only_tables.map((t) => `\`${t}\``).join(', ')}): as above, except the project's own student.`,
  ...reads.views.map(
    (v) =>
      `- \`${v.view}\` where \`${v.where}\`: ${v.visible.map((c) => short[c] ?? c).join(', ')}.`,
  ),
  '- **Direct writes**: no caller can insert, update or delete any table directly; every change goes through the functions above (SEC-09).',
  '',
);
const text = lines.join('\n');

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    /* missing */
  }
  if (current !== text) {
    console.error(
      'docs/PERMISSION_MATRIX.md is out of date: run node scripts/permission-matrix.mjs',
    );
    process.exit(1);
  }
  console.log('✓ docs/PERMISSION_MATRIX.md matches the permission matrix');
} else {
  writeFileSync(target, text);
  console.log('✓ wrote docs/PERMISSION_MATRIX.md');
}
